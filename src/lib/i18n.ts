export function t(
  lang: Language,
  key: string,
  params?: Record<string, string | number>,
): string {
  const catalog = CATALOGS[lang] ?? CATALOGS.en;
  let text = catalog[key] ?? CATALOGS.en[key] ?? key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}
